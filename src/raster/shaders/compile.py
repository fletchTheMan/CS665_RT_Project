#!/usr/bin/env python3
"""Compile the raster GLSL shaders and regenerate src/raster/raster_shaders.h.

Run this from anywhere after editing a shader:
    python3 src/raster/shaders/compile.py

Requires glslangValidator on PATH. The generated header is checked in so a
normal build does not need glslangValidator installed.
"""

from pathlib import Path
import subprocess
import sys

SHADER_DIR = Path(__file__).resolve().parent
OUTPUT_HEADER = SHADER_DIR.parent / "raster_shaders.h"


def compile_shader(source: Path, stage: str, output: Path) -> bytes:
    subprocess.run(
        [
            "glslangValidator",
            "-V",
            "--target-env",
            "vulkan1.3",
            "-S",
            stage,
            str(source),
            "-o",
            str(output),
        ],
        check=True,
    )
    return output.read_bytes()


def as_words(blob: bytes) -> list[int]:
    if len(blob) % 4 != 0:
        raise RuntimeError("SPIR-V size is not a multiple of four")
    return [
        int.from_bytes(blob[i : i + 4], byteorder="little", signed=False)
        for i in range(0, len(blob), 4)
    ]


def array_declaration(name: str, words: list[int]) -> str:
    lines = [f"inline constexpr uint32_t {name}[] = {{"]
    for start in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[start : start + 8]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    try:
        import tempfile
        with tempfile.TemporaryDirectory() as tmp:
            tmp_dir = Path(tmp)
            vert = compile_shader(SHADER_DIR / "raster.vert", "vert", tmp_dir / "raster.vert.spv")
            frag = compile_shader(SHADER_DIR / "raster.frag", "frag", tmp_dir / "raster.frag.spv")
    except FileNotFoundError:
        print("glslangValidator not found on PATH", file=sys.stderr)
        return 1

    contents = f"""// Generated by src/raster/shaders/compile.py -- do not edit by hand.
// Sources: src/raster/shaders/raster.vert and src/raster/shaders/raster.frag
#pragma once

#include <cstdint>

{array_declaration("raster_vert_spv", as_words(vert))}

{array_declaration("raster_frag_spv", as_words(frag))}

inline constexpr size_t raster_vert_spv_size = sizeof(raster_vert_spv);
inline constexpr size_t raster_frag_spv_size = sizeof(raster_frag_spv);
"""
    OUTPUT_HEADER.write_text(contents)
    print(f"wrote {OUTPUT_HEADER}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
